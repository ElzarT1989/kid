CURRICULUM_TEMPLATES: dict[int, list[Module]] = {
    2: MODULES_AGE_2,
    5: MODULES_AGE_5,
}

WEEKS_PER_MODULE = 4
MODULES_PER_YEAR = 12
CYCLE_LENGTH_WEEKS = WEEKS_PER_MODULE * MODULES_PER_YEAR  # 48


def get_template_for_age(age: int) -> list[Module]:
    """Ближайший определённый профиль (2 или 5), если возраст не совпадает
    с ними в точности — на будущее, если профили ChildProfile.age станут
    произвольными."""
    if age in CURRICULUM_TEMPLATES:
        return CURRICULUM_TEMPLATES[age]
    closest_age = min(CURRICULUM_TEMPLATES, key=lambda a: abs(a - age))
    return CURRICULUM_TEMPLATES[closest_age]


def get_topic(age: int, month: int, week: int) -> WeeklyTopic:
    """month/week — 1-based, как в CurriculumNode. Год закольцован
    (после месяца 12/недели 4 план начинается заново)."""
    modules = get_template_for_age(age)
    flat_index = ((month - 1) * WEEKS_PER_MODULE + (week - 1)) % CYCLE_LENGTH_WEEKS
    module_index, week_index = divmod(flat_index, WEEKS_PER_MODULE)
    return modules[module_index][week_index]


def next_month_week(month: int, week: int) -> tuple[int, int]:
    flat_index = (month - 1) * WEEKS_PER_MODULE + (week - 1)
    next_flat_index = (flat_index + 1) % CYCLE_LENGTH_WEEKS
    next_month = next_flat_index // WEEKS_PER_MODULE + 1
    next_week = next_flat_index % WEEKS_PER_MODULE + 1
    return next_month, next_week
